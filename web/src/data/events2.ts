import type { AccessInfo, EventItem, Lang, SourceName } from '../types';

const c = (present: boolean, note?: string): AccessInfo => ({ present, evidence: 'confirmed', note });
const est = (present: boolean, note?: string): AccessInfo => ({ present, evidence: 'estimated', note });
const unk = (): AccessInfo => ({ present: false, evidence: 'unknown' });
const synced = '2026-10-24T09:00:00-04:00';

interface Def {
  id: string;
  title: string;
  summary: string;
  category: EventItem['category'];
  start: string;
  end: string;
  price?: number;
  venue: string;
  address: string;
  lat: number;
  lng: number;
  languages: Lang[];
  audience: string;
  volunteer?: boolean;
  source: SourceName;
  rating?: [number, number];
  access: EventItem['access'];
  stop: string;
  walk: number;
  routes: string[];
  service?: boolean;
  parking: EventItem['parking'];
  signals: [number, number, number, number];
  host: string;
  hostBlurb: string;
  spots?: [number, number];
}

function ev(d: Def): EventItem {
  return {
    id: d.id,
    title: d.title,
    summary: d.summary,
    category: d.category,
    start: d.start,
    end: d.end,
    free: d.price === undefined,
    price: d.price,
    venue: d.venue,
    address: d.address,
    lat: d.lat,
    lng: d.lng,
    languages: d.languages,
    audience: d.audience,
    volunteer: d.volunteer ?? false,
    source: {
      name: d.source,
      url: '#',
      rating: d.rating?.[0],
      reviewCount: d.rating?.[1],
      lastSynced: synced,
    },
    access: d.access,
    transit: { stop: d.stop, walkMeters: d.walk, routes: d.routes, serviceAtStart: d.service ?? true },
    parking: d.parking,
    signals: { saves: d.signals[0], signups: d.signals[1], comments: d.signals[2], views: d.signals[3] },
    image: '',
    hostName: d.host,
    hostBlurb: d.hostBlurb,
    spots: d.spots ? { left: d.spots[0], total: d.spots[1] } : undefined,
  };
}

